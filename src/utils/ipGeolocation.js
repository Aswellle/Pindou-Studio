/**
 * IP 地址分类(纯函数)。
 *
 * 历史:后台用户列表曾按需调用 ipwho.is 查询归属地。那会把用户 IP
 * 发送给未在隐私政策披露的第三方,已移除外部查询;现在只保留内网/
 * 保留地址判定,公网 IP 原样展示,不再离开本站。
 */

/** 内网 / 保留地址:没有公网归属地,也不应触发任何外部查询 */
export function isPrivateIp(ip) {
  const s = String(ip || '').trim()
  if (!s) return true
  return (
    /^(127\.|10\.|192\.168\.|169\.254\.|0\.)/.test(s) ||
    /^172\.(1[6-9]|2\d|3[01])\./.test(s) ||
    /^(::1|f[cd][0-9a-f]{2}:)/i.test(s) ||
    s === 'localhost'
  )
}
